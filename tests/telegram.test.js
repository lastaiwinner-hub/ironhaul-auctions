'use strict';
const {test,after}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'auction-telegram-'));
process.env.NODE_ENV='test';process.env.DATABASE_FILE=path.join(dir,'test.sqlite');
process.env.TELEGRAM_ENABLED='false';
fs.copyFileSync(path.join(__dirname,'../db/demo.sqlite'),process.env.DATABASE_FILE);
const {db,migrate}=require('../config/database');migrate();
const config=require('../config'),chat=require('../src/services/engagement'),alerts=require('../src/services/telegram');
const originalFetch=global.fetch;
after(()=>{global.fetch=originalFetch;db.close();fs.rmSync(dir,{recursive:true,force:true});});
test('visitor alerts are opt-in, deduplicated, private and retried after provider limits',async()=>{
 db.prepare('INSERT INTO support_threads(id,name,email,created_at,updated_at) VALUES (?,?,?,?,?)').run('alert-test','Private Name','private@example.test',Date.now(),Date.now());
 chat.addMessage('alert-test','visitor','Private message','disabled');
 assert.equal(db.prepare('SELECT COUNT(*) n FROM support_alerts').get().n,0);
 Object.assign(config.telegram,{enabled:true,botToken:'fake-test-token',chatId:'123',inboxUrl:'https://example.test/staff/inbox'});
 chat.addMessage('alert-test','visitor','Private message','message-1');
 chat.addMessage('alert-test','visitor','Private message','message-1');
 chat.addMessage('alert-test','team','Team reply','reply-1');
 assert.equal(db.prepare('SELECT COUNT(*) n FROM support_alerts').get().n,1);
 let calls=0;
 global.fetch=async(url,options)=>{calls++;const payload=JSON.parse(options.body);assert.equal(payload.chat_id,'123');assert.match(payload.text,/https:\/\/example.test\/staff\/inbox/);assert.doesNotMatch(payload.text,/Private|private@example|Team reply/);return {ok:false,json:async()=>({ok:false,parameters:{retry_after:120}})};};
 const now=Date.now();await alerts.flush();let row=db.prepare('SELECT * FROM support_alerts').get();
 assert.equal(row.attempts,1);assert.ok(row.next_attempt>=now+120000);assert.equal(row.sent_at,null);
 await alerts.flush();assert.equal(calls,1);
 db.prepare('UPDATE support_alerts SET next_attempt=0').run();
 global.fetch=async()=>{calls++;return {ok:true,json:async()=>({ok:true})};};
 await alerts.flush();await alerts.flush();assert.equal(calls,2);assert.ok(db.prepare('SELECT sent_at FROM support_alerts').get().sent_at);
 chat.addMessage('alert-test','visitor','Another private message','message-2');
 global.fetch=async()=>{throw Error('network error with secret URL');};await alerts.flush();
 assert.equal(db.prepare('SELECT attempts FROM support_alerts WHERE sent_at IS NULL').get().attempts,1);
});
